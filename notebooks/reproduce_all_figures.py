# %% [markdown]
# # Reproduce every MutPred-PPI figure and table, from scratch
#
# Runner notebook for the MutPred-PPI publication repo. Given the Zenodo
# deposit (`datasets/`, `weights/`) it regenerates, in order: stability
# pretraining -> the canonical data layer and contact-graph store ->
# embeddings for every method -> group cross-validation (GCV) -> the
# VarChAMP blind test -> the final all-data model -> variant-repository
# inference -> every manuscript figure and table.
#
# **Caching.** Every step checks whether its output already exists before
# doing anything, so a second run of the whole notebook with `FORCE=False`
# finishes in well under a minute. Embedding/GCV/inference scripts also
# resume by content key internally, so re-running one is cheap even after a
# partial failure.
#
# **QUICK mode.** `QUICK=True` runs 1 GCV seed (not 30), subsamples the
# variant databases, and shrinks the enrichment bootstraps -- the whole
# pipeline finishes in hours instead of the days a full run takes, for
# smoke-testing the chain. **Quick-mode output never touches the canonical
# `results/` tree that `figures/*.png` symlink into** -- it is redirected to
# a sandbox via `MUTPRED_PPI_RESULTS_DIR` (see `src/paths.py`).
#
# **Only `datasets/training_eval/` data is ever read.** Every dataset name is
# one of the five `*_mapped090826` configs in `utils.gcv_common.DATASET_CONFIGS`;
# `utils.legacy_guard` raises rather than silently accepting anything from the
# retired pre-090826 pipeline (`.mat`/`.pos`/`.neg`/`.labels`/`.vt_ids` files,
# `all_vt_ids_and_labels.txt`, `sfvcfp_rows.csv.gz`, `training_data_internal.csv`,
# ...). See `docs/FIGURE_INVENTORY.md` for the full inventory this notebook
# was built to satisfy, and `docs/REPRODUCING_ANALYSES.md` for the underlying
# per-script commands this notebook wraps.
#
# **Data is not final.** AF3 structures were still generating when this
# notebook was written (2026-09-10); run it once whatever exists to
# smoke-test the chain, and again in full once the AF3 run completes.
#
# **Not reproducible here, by design:**
# Fig 4/S2 and Table 1 need unpublished VarChAMP data, present only in
# `datasets/training_eval/varchamp_all_mapped090826_rows.csv.gz`; those steps
# detect its absence and skip with a clear message rather than failing. Figs
# 1 and 2 (pipeline, architecture) and the CDC42 example panel are drawn by
# hand and are not regenerated by anything in this repo.

