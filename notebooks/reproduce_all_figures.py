def run(cmd: list, *, produces: list | None = None, name: str | None = None,
       cwd: Path | None = None) -> None:
    """Run a command, skipping it if every `produces` path already exists.

    This is the whole caching layer: a second notebook run with
    `FORCE=False` finds every `produces` path present and does nothing.
    """
    label = name or Path(str(cmd[2]) if len(cmd) > 2 else cmd[0]).name
    produces = [Path(p) for p in (produces or [])]
    if produces and not FORCE and all(p.exists() for p in produces):
        print(f"[cached]  {label}  ({len(produces)} output(s) present)")
        return
    print(f"[run]     {label}")
    print(f"          {' '.join(str(c) for c in cmd)}")
    if DRY_RUN:
        return
    t0 = time.time()
    result = subprocess.run(cmd, cwd=str(cwd or REPO), env=_ENV,
                            capture_output=True, text=True)
    dt = time.time() - t0
    tail = "\n".join(result.stdout.splitlines()[-20:])
    print(tail)
    if result.returncode != 0:
        print(result.stderr[-4000:])
        raise RuntimeError(f"{label} failed (exit {result.returncode}) after {dt:.0f}s")
    print(f"          done in {dt:.0f}s")


def show(path, caption: str = "") -> None:
    """Display a figure inline; warn (don't raise) if it isn't there yet."""
    path = Path(path)
    if not path.exists():
        print(f"[missing] {caption or path.name}: {path}")
        return
    print(f"{caption or path.name}  ->  {path}")
    display(Image(filename=str(path)))


def assert_fresh(*paths) -> None:
    """Refuse pre-090826 artifacts -- thin wrapper over utils.legacy_guard."""
    reject_legacy(*paths)


def subsample_rows(db: str, n: int, seed: int = 0) -> Path:
    """A seeded subsample of a variant-DB row table, for QUICK-mode --rows."""
    src = DATASETS_DIR / "variant_dbs" / f"{db}_rows.csv.gz"
    out_dir = _RESULTS_DIR / "_quick_subsamples"
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"{db}_rows_n{n}.csv.gz"
    if out.exists() and not FORCE:
        return out
    df = pd.read_csv(src)
    df.sample(n=min(n, len(df)), random_state=seed).to_csv(out, index=False)
    return out


